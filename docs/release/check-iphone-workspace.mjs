// Browser emulation and synthetic pointer events; not physical iPhone qualification.
import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
const { webkit } = await import(process.env.LUMA_PLAYWRIGHT_MODULE ?? "playwright");
const base = process.env.LUMA_UI_URL ?? "http://localhost:4184/iphone";
assert.ok(["localhost", "127.0.0.1", "[::1]"].includes(new URL(base).hostname));
const output = await mkdtemp(resolve("artifacts/iphone-workspace-"));
const browser = await webkit.launch({ headless: true });
const report = { scope: "WebKit phone layouts, real controls and synthetic pointer handlers; not hardware, offline or iOS Files qualification", pass: false, checks: [], errors: [] };
let phase = "startup", page;
const watchdog = setTimeout(() => void browser.close(), 240000);
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, deviceScaleFactor: 2 });
  await context.addInitScript(() => localStorage.setItem("luma.scripting", "on"));
  page = await context.newPage();
  page.on("pageerror", error => report.errors.push(`${phase}: ${error.stack ?? String(error)}`));
  await page.route("**/*", route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
  await page.goto(base, { waitUntil: "domcontentloaded", timeout: 120000 });
  await page.waitForFunction(() => window.luma?.studio.doc.layers.length > 0, { timeout: 90000 });
  await page.getByRole("status", { name: "Restoring workspace" }).waitFor({ state: "hidden" });
  await page.locator('[data-form-factor="phone"]').waitFor();
  await page.getByRole("button", { name: "Touch: draw", exact: true }).waitFor();
  phase = "layouts";
  for (const [width, height] of [[320, 568], [375, 667], [390, 844], [430, 932], [667, 375], [844, 390]]) {
    await page.setViewportSize({ width, height });
    await page.waitForFunction(h => Math.abs(document.querySelector('[data-app-shell]').getBoundingClientRect().height - h) < 2, height);
    for (const name of ["Save project", "Undo", "Redo", "Export", "Toggle layers panel", "Toggle properties panel"]) {
      const box = await page.getByRole("button", { name, exact: true }).boundingBox();
      assert.ok(box && box.x >= 0 && box.x + box.width <= width + 1 && box.y >= 0 && box.y + box.height <= height, `${name} clipped at ${width}×${height}: ${JSON.stringify(box)}`);
      assert.ok(box.height >= 44, `${name} needs a touch target`);
    }
    const canvas = await page.locator("#studio-canvas").boundingBox();
    assert.ok(canvas.width > width - 20 && canvas.height >= 110, `canvas too small: ${JSON.stringify(canvas)}`);
    await page.screenshot({ path: join(output, `phone-${width}x${height}.png`) });
  }
  report.checks.push("Six portrait/landscape sizes: actions reachable, touch targets and canvas bounds");
  await page.setViewportSize({ width: 390, height: 844 });
  phase = "panels";
  await page.getByRole("button", { name: "Toggle layers panel" }).tap();
  const picker = page.getByRole("combobox", { name: "Workspace panel" });
  assert.equal(await picker.locator("option").count(), 22);
  await picker.selectOption("paint");
  await page.waitForFunction(() => document.querySelector(".tablet-panel .dock-panel-body input") !== null);
  await page.screenshot({ path: join(output, "phone-brush-panel.png") });
  await page.getByRole("button", { name: "Close workspace panel" }).tap();
  await page.getByRole("button", { name: "Paint tools", exact: true }).tap();
  assert.equal(await page.locator('.tool-family-menu').count(), 0, 'tap selects the tool, not its context menu');
  await page.getByRole("button", { name: "Paint tools", exact: true }).focus();
  await page.keyboard.press('ArrowRight');
  await page.getByRole("button", { name: "Close related tools" }).waitFor();
  assert.ok(await page.locator('.tool-family-menu').evaluate(el => el.contains(document.activeElement)), "tool sheet owns keyboard focus");
  await page.getByRole("menuitem", { name: /^Brush/ }).first().tap();
  assert.equal(await page.locator(".tablet-panel").count(), 0, "choosing a tool returns to the canvas");
  report.checks.push("All registered panels available; tool selection returns to canvas");
  phase = "touch browsing and menu dismissal";
  await page.getByRole("button", { name: "Toggle layers panel" }).tap();
  await page.getByRole("button", { name: "More tools and command search" }).tap();
  assert.equal(await page.locator('.tool-palette').evaluate(el => document.activeElement === el), true, "touch browsing must not autofocus the software keyboard");
  await page.keyboard.press("Escape");
  assert.equal(await page.locator('.tool-palette').count(), 0);
  assert.equal(await page.locator('.tablet-panel').count(), 1, "closing tool search must not close the panel behind it");
  await page.getByRole("button", { name: "Close workspace panel" }).tap();
  await page.setViewportSize({ width: 320, height: 568 });
  await page.getByLabel("More application actions", { exact: true }).tap();
  const menuBox = await page.locator('.studio-app-menu > div').boundingBox();
  assert.ok(menuBox && menuBox.x >= 0 && menuBox.x + menuBox.width <= 321, "application menu stays inside the narrowest screen");
  await page.keyboard.press("Escape");
  assert.equal(await page.locator('.studio-app-menu').getAttribute('open'), null);
  await page.setViewportSize({ width: 390, height: 844 });
  report.checks.push("Touch tool browsing avoids input autofocus; Escape dismisses only its overlay; narrow-screen menu bounds");
  phase = "drawing";
  const canvas = page.locator("#studio-canvas canvas").filter({ visible: true }).first();
  // Synthetic events do not have OS pointer capture. Only capture is shimmed.
  await canvas.evaluate(e => { e.setPointerCapture = () => {}; e.releasePointerCapture = () => {}; });
  const box = await canvas.boundingBox();
  const pointer = (type, id, x, y) => canvas.dispatchEvent(type, { pointerId: id, pointerType: "touch", clientX: box.x + x, clientY: box.y + y, button: 0, buttons: type === "pointerup" ? 0 : 1, bubbles: true });
  const depth = await page.evaluate(() => window.luma.studio.historyState().currentDepth);
  await pointer("pointerdown", 1, 100, 140); await pointer("pointermove", 1, 200, 180); await pointer("pointerup", 1, 200, 180);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), depth + 1);
  await page.getByRole("button", { name: "Undo", exact: true }).tap();
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), depth);
  await page.getByRole("button", { name: "Redo", exact: true }).tap();
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), depth + 1);
  await pointer("pointerdown", 1, 100, 140); await pointer("pointermove", 1, 150, 180); await pointer("pointercancel", 1, 150, 180);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), depth + 1);
  await page.getByRole("button", { name: "Touch: draw", exact: true }).tap();
  const scale = await page.evaluate(() => window.luma.studio.displayViewport.cssScale);
  await pointer("pointerdown", 1, 100, 140); await pointer("pointerdown", 2, 180, 140);
  await pointer("pointermove", 2, 260, 140); await pointer("pointerup", 2, 260, 140); await pointer("pointerup", 1, 100, 140);
  await page.waitForFunction(s => window.luma.studio.displayViewport.cssScale > s, scale);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), depth + 1);
  assert.equal(await page.evaluate(() => localStorage.getItem("luma.tablet.finger-drawing.v1")), null);
  report.checks.push("Finger stroke, undo, redo, cancellation and non-editing pinch; separate phone preference");
  phase = "export";
  await page.getByRole("button", { name: "Export", exact: true }).tap();
  const exportBox = await page.locator(".studio-export-popover").boundingBox();
  assert.ok(exportBox && exportBox.x >= 0 && exportBox.x + exportBox.width <= 391);
  const format = page.getByRole("combobox", { name: "Raster export format" });
  assert.ok((await format.boundingBox()).width >= 120, "export format must not collapse to an icon-sized column");
  await format.selectOption("jpeg");
  await page.getByRole("button", { name: "Export JPEG", exact: true }).waitFor();
  await page.screenshot({ path: join(output, "phone-export.png") });
  report.checks.push("Export controls fit the phone viewport");
  await page.getByRole("button", { name: "Close export menu" }).tap();
  phase = "document safety";
  const active = await page.evaluate(() => window.luma.studio.activeDocumentState());
  await page.getByLabel("More application actions", { exact: true }).tap();
  await page.getByRole("button", { name: "Close document…", exact: true }).tap();
  const confirmation = page.getByRole("dialog", { name: /Save changes/ });
  await confirmation.waitFor();
  await confirmation.getByRole("button", { name: "Cancel", exact: true }).tap();
  assert.equal(await page.evaluate(() => window.luma.studio.activeDocumentState().id), active.id);
  assert.equal(await page.evaluate(() => window.luma.studio.activeDocumentState().dirty), true);
  report.checks.push("Dirty tab close prompts; Cancel preserves the document");
  assert.equal(report.errors.length, 0);
  report.pass = true;
} finally {
  if (page && !page.isClosed()) await page.screenshot({ path: join(output, "last-state.png") }).catch(() => {});
  clearTimeout(watchdog); await browser.close();
  await writeFile(join(output, "report.json"), JSON.stringify(report, null, 2));
  console.log(output); console.log(JSON.stringify(report, null, 2));
}
