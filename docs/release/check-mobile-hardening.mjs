// Isolated WebKit UI regression campaign; not physical iOS qualification.
import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
const { webkit } = await import(process.env.LUMA_PLAYWRIGHT_MODULE ?? "playwright");
const base = process.env.LUMA_UI_URL ?? "http://localhost:4184/iphone";
assert.ok(["localhost", "127.0.0.1"].includes(new URL(base).hostname));
const output = await mkdtemp(resolve("artifacts/mobile-hardening-"));
const browser = await webkit.launch({ headless: true });
const report = { pass: false, checks: [], errors: [], output };
const watchdog = setTimeout(() => void browser.close(), 240000);
let page;
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  await context.addInitScript(() => localStorage.setItem("luma.scripting", "on"));
  page = await context.newPage();
  page.on("pageerror", e => report.errors.push(String(e)));
  await page.route("**/*", r => new URL(r.request().url()).origin === new URL(base).origin ? r.continue() : r.abort());
  await page.goto(base, { waitUntil: "domcontentloaded", timeout: 90000 });
  await page.waitForFunction(() => window.luma?.studio.doc.layers.length > 0, { timeout: 90000 });
  await page.getByRole("status", { name: "Restoring workspace" }).waitFor({ state: "hidden" });
  for (const [width, height] of [[320, 568], [390, 844], [844, 390]]) {
    await page.setViewportSize({ width, height });
    await page.waitForFunction(h => Math.abs(document.querySelector('[data-app-shell]').getBoundingClientRect().height - h) < 2, height);
    const stage = await page.locator("#studio-canvas").boundingBox();
    assert.ok(stage.height >= height * .53, `Canvas cramped: ${width}×${height}: ${stage.height}`);
    assert.ok(await page.locator(".phone-document-status").isVisible());
    await page.screenshot({ path: join(output, `base-${width}.png`), animations: "disabled" });
  }
  report.checks.push("Phone and landscape canvas bounds; persistent save status");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Toggle layers panel" }).tap();
  await page.locator('.spatial-layer[role="option"]').first().waitFor();
  assert.equal(await page.locator('.tablet-panel').getAttribute('data-size'), 'half');
  await page.getByRole("button", { name: "Expand", exact: true }).tap();
  const picker = page.getByRole("combobox", { name: "Workspace panel" });
  assert.equal(await picker.locator('option').count(), 22);
  assert.ok((await picker.boundingBox()).height >= 44);
  await page.getByRole("button", { name: "Add paint layer", exact: true }).tap();
  await page.getByRole("button", { name: "Select layers", exact: true }).tap();
  await page.locator('.spatial-layer[role="option"][aria-selected="false"]').first().tap();
  assert.equal(await page.locator('.spatial-layer[aria-selected="true"]').count(), 2);
  await page.getByRole('button', { name: 'Actions · 2', exact: true }).tap();
  await page.getByRole('menu', { name: 'Layer context actions' }).waitFor();
  assert.ok(await page.getByRole('menuitem', { name: /Group/ }).first().isEnabled());
  await page.getByRole('menuitem', { name: /^Group/ }).first().tap();
  await page.waitForFunction(() => window.luma.studio.doc.layers.some(layer => layer.kind === 'group'));
  await page.getByRole('button', { name: 'Undo', exact: true }).tap();
  await page.waitForFunction(() => !window.luma.studio.doc.layers.some(layer => layer.kind === 'group'));
  await page.screenshot({ path: join(output, 'layers.png'), animations: 'disabled' });
  await page.getByRole('button', { name: 'Done selecting', exact: true }).tap();
  await page.locator('.spatial-layer[role="option"]').first().tap();
  assert.ok((await page.locator('.virtual-layer-stack').boundingBox()).height >= 92);
  await page.locator('.blend-pass').first().waitFor();
  assert.equal(await page.locator('.blend-pass').first().evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(41, 45, 51)');
  for (const id of ['properties', 'document', 'vector', 'paint']) {
    await picker.selectOption(id);
    await page.getByText('Loading typography…', { exact: true }).waitFor({ state: 'hidden' });
    await page.locator('.tablet-panel .dock-panel-body').evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const cards = await page.locator('.tablet-panel .glass-card').evaluateAll(es => es.map(e => getComputedStyle(e).backgroundColor));
    assert.ok(cards.every(c => c === 'rgb(32, 35, 40)'), `${id}: ${cards}`);
    await page.screenshot({ path: join(output, `${id}.png`), animations: 'disabled' });
  }
  report.checks.push("22 grouped panels, sheet sizing, dark cards, touch multi-selection and actions");
  await page.getByRole('button', { name: 'Close workspace panel' }).tap();
  await page.getByRole('button', { name: 'Paint tools', exact: true }).tap();
  assert.equal(await page.locator('.tool-family-menu').count(), 0);
  const canvas = page.locator('#studio-canvas canvas').filter({ visible: true }).first();
  await canvas.evaluate(e => { e.setPointerCapture = () => {}; e.releasePointerCapture = () => {}; });
  const bounds = await canvas.boundingBox();
  const pointer = (type, id, x, y) => canvas.dispatchEvent(type, { pointerId: id, pointerType: 'touch', clientX: bounds.x + x, clientY: bounds.y + y, button: 0, buttons: type === 'pointerup' ? 0 : 1, bubbles: true });
  const before = await page.evaluate(() => ({ depth: window.luma.studio.historyState().currentDepth, scale: window.luma.studio.displayViewport.cssScale }));
  await pointer('pointerdown', 1, 110, 130); await pointer('pointermove', 1, 120, 135);
  await pointer('pointerdown', 2, 210, 135); await pointer('pointermove', 2, 270, 135);
  await pointer('pointerup', 2, 270, 135); await pointer('pointerup', 1, 120, 135);
  await page.waitForFunction(scale => window.luma.studio.displayViewport.cssScale > scale, before.scale);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), before.depth);
  await pointer('pointerdown', 3, 100, 130); await pointer('pointermove', 3, 180, 170); await pointer('pointerup', 3, 180, 170);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), before.depth + 1);
  report.checks.push("Finger stroke → pinch rolls back without history, subsequent stroke still works");
  await page.getByRole('button', { name: 'Export', exact: true }).tap();
  await page.getByRole('combobox', { name: 'Raster export format' }).waitFor();
  assert.match(await page.locator('.studio-export-options article').first().innerText(), /Raster image/);
  await page.screenshot({ path: join(output, 'export.png'), animations: 'disabled' });
  await page.getByRole('button', { name: 'Close export menu' }).tap();
  await page.getByLabel('More application actions', { exact: true }).tap();
  await page.getByRole('button', { name: 'Focus canvas', exact: true }).tap();
  await page.waitForFunction(() => document.querySelector('#studio-canvas').getBoundingClientRect().height > 700);
  await page.getByRole('button', { name: 'Show controls', exact: true }).tap();
  report.checks.push('Raster-first export and reversible canvas-focus mode');
  await page.getByRole('button', { name: 'Save project', exact: true }).first().tap();
  await page.getByRole('dialog', { name: 'Check your downloaded project' }).waitFor({ timeout: 90000 });
  assert.equal(await page.evaluate(() => window.luma.studio.activeDocumentState().dirty), true);
  await page.getByRole('button', { name: 'Keep document unsaved', exact: true }).tap();
  assert.equal(await page.evaluate(() => window.luma.studio.activeDocumentState().dirty), true);
  await page.getByRole('button', { name: 'Save project', exact: true }).first().tap();
  await page.getByRole('dialog', { name: 'Check your downloaded project' }).waitFor({ timeout: 90000 });
  await page.getByRole('button', { name: 'I verified the saved file', exact: true }).tap();
  await page.waitForFunction(() => !window.luma.studio.activeDocumentState().dirty);
  await page.evaluate(() => { const s = window.luma.studio; s.setLayerProp(s.doc.layers[0].id, 'opacity', .7, 'Test edit'); });
  await page.getByRole('button', { name: 'Save project', exact: true }).first().tap();
  await page.getByRole('dialog', { name: 'Check your downloaded project' }).waitFor({ timeout: 90000 });
  // A remote/script edit can arrive while application controls are inert.
  await page.evaluate(() => { const s = window.luma.studio; s.setLayerProp(s.doc.layers[0].id, 'opacity', .6, 'Newer test edit'); });
  await page.getByRole('button', { name: 'I verified the saved file', exact: true }).tap();
  await page.waitForFunction(() => !document.querySelector('.spatial-window').inert);
  assert.equal(await page.evaluate(() => window.luma.studio.activeDocumentState().dirty), true);
  await page.getByLabel('More application actions', { exact: true }).tap();
  await page.getByRole('button', { name: 'Close document…', exact: true }).tap();
  const close = page.getByRole('dialog', { name: /Save changes/ });
  await close.waitFor();
  await close.getByRole('button', { name: 'Cancel', exact: true }).tap();
  report.checks.push('Unconfirmed downloads stay dirty; verified downloads settle only their revision; close still prompts after newer edits');
  assert.deepEqual(report.errors, []);
  report.pass = true;
} finally {
  if (page && !page.isClosed()) await page.screenshot({ path: join(output, 'last-state.png'), animations: 'disabled' }).catch(() => {});
  clearTimeout(watchdog); await browser.close();
  await writeFile(join(output, 'report.json'), JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
}
