// Browser emulation is NOT physical iPad / Apple Pencil qualification.
import assert from "node:assert/strict";
import { mkdtemp, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
const { webkit } = await import(process.env.LUMA_PLAYWRIGHT_MODULE ?? "playwright");
const base = process.env.LUMA_UI_URL ?? "http://127.0.0.1:4183/?interface=tablet";
assert.ok(["127.0.0.1", "localhost", "[::1]"].includes(new URL(base).hostname));
const output = await mkdtemp(resolve("artifacts/ipad-workspace-"));
const browser = await webkit.launch({ headless: true });
const report = { scope: "WebKit touch emulation and synthetic PointerEvents; not physical iPad/Pencil, native packaging, or offline qualification", pass: false, errors: [], checks: [] };
let phase = "startup";
const watchdog = setTimeout(() => void browser.close(), 240000);
try {
  const context = await browser.newContext({ viewport: { width: 1194, height: 834 }, hasTouch: true, deviceScaleFactor: 2 });
  await context.addInitScript(() => localStorage.setItem("luma.scripting", "on"));
  const page = await context.newPage();
  page.on("pageerror", error => report.errors.push(`${phase}: ${error.stack ?? String(error)}`));
  await page.route("**/*", route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
  await page.goto(base, { waitUntil: "domcontentloaded", timeout: 120000 });
  await page.waitForFunction(() => window.luma?.studio.doc.layers.length > 0, { timeout: 120000 });
  await page.getByRole("status", { name: "Restoring workspace" }).waitFor({ state: "hidden" });
  await page.locator('[data-interface="tablet"]').waitFor();
  phase = "panels";
  await page.getByRole("button", { name: "Toggle layers panel" }).tap();
  await page.getByRole("complementary", { name: "Workspace panel" }).waitFor();
  const panels = page.getByRole("combobox", { name: "Workspace panel" });
  assert.equal(await panels.locator("option").count(), 22);
  await panels.selectOption("paint");
  await page.waitForFunction(() => document.querySelector(".tablet-panel .dock-panel-body input") !== null);
  assert.equal(await panels.inputValue(), "paint");
  await page.getByRole("button", { name: "Close workspace panel" }).tap();
  await page.getByRole("button", { name: "Paint tools", exact: true }).tap();
  assert.equal(await page.locator('.tool-family-menu').count(), 0, 'one tap selects the painting tool');
  report.checks.push("Registry drawer and direct tap-to-select tool");
  phase = "navigation";
  // Use real pointer handlers with a capture shim: synthetic pointers have no OS capture.
  const before = await page.evaluate(() => {
    const s = window.luma.studio;
    return { depth: s.historyState().currentDepth, viewport: s.displayViewport };
  });
  const canvas = page.locator("#studio-canvas canvas").filter({ visible: true }).first();
  await canvas.evaluate(element => { element.setPointerCapture = () => {}; element.releasePointerCapture = () => {}; });
  const box = await canvas.boundingBox(); assert.ok(box.width > 500 && box.height > 250);
  const pointer = async (type, id, x, y, extra = {}) => {
    await canvas.dispatchEvent(type, { pointerId: id, pointerType: "touch", isPrimary: id === 1, clientX: box.x + x, clientY: box.y + y, button: 0, buttons: type === "pointerup" ? 0 : 1, bubbles: true, ...extra });
  };
  await pointer("pointerdown", 1, 200, 200);
  await pointer("pointermove", 1, 240, 230);
  await pointer("pointerdown", 2, 340, 230);
  await pointer("pointermove", 2, 400, 230);
  await pointer("pointerup", 2, 400, 230);
  await pointer("pointerup", 1, 240, 230);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), before.depth, "navigation must not paint");
  await page.waitForFunction(zoom => window.luma.studio.displayViewport.cssScale > zoom, before.viewport.cssScale);
  report.checks.push("Finger pan/pinch creates no edit history");
  phase = "drawing";
  await page.getByRole("button", { name: "Touch: navigate", exact: true }).tap();
  await pointer("pointerdown", 1, 200, 200);
  await pointer("pointermove", 1, 300, 200);
  await pointer("pointerdown", 2, 360, 220);
  await pointer("pointerup", 2, 360, 220);
  await pointer("pointermove", 1, 340, 200);
  await pointer("pointerup", 1, 340, 200);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), before.depth, "second finger cancels the provisional finger stroke before navigation");
  await pointer("pointerdown", 3, 200, 200);
  await pointer("pointermove", 3, 300, 200);
  await pointer("pointerup", 3, 300, 200);
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), before.depth + 1, "one owned finger stroke");
  await page.getByRole("button", { name: "Undo", exact: true }).tap();
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), before.depth);
  report.checks.push("Finger drawing, second-finger rollback/navigation, subsequent stroke and undo");
  await pointer("pointerdown", 10, 200, 200, { pointerType: "pen", pressure: 0.3, tiltX: 25 });
  await pointer("pointermove", 10, 290, 220, { pointerType: "pen", pressure: 0.8, tiltX: 35 });
  await pointer("pointerdown", 11, 400, 230);
  await pointer("pointerup", 11, 400, 230);
  await pointer("pointercancel", 10, 290, 220, { pointerType: "pen" });
  assert.equal(await page.evaluate(() => window.luma.studio.historyState().currentDepth), before.depth, "cancelled Pencil stroke adds no history");
  report.checks.push("Synthetic Pencil pressure/tilt path with palm isolation and cancellation");
  phase = "orientation";
  if (await page.getByRole("button", { name: "Close workspace panel" }).isVisible()) await page.getByRole("button", { name: "Close workspace panel" }).tap();
  await page.screenshot({ path: join(output, "landscape.png") });
  await page.setViewportSize({ width: 834, height: 1194 });
  await page.getByRole("button", { name: "Toggle layers panel" }).tap();
  await page.screenshot({ path: join(output, "portrait-layers.png") });
  const bounds = await page.locator(".tablet-panel").boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 834 && bounds.y + bounds.height <= 1194);
  await page.getByRole("button", { name: "Close workspace panel" }).tap();
  phase = "reload";
  await page.reload();
  await page.getByRole("button", { name: "Touch: draw", exact: true }).waitFor({ state: "visible", timeout: 60000 });
  report.checks.push("Portrait bounds and touch-mode persistence");
  await page.setViewportSize({ width: 600, height: 900 });
  await page.screenshot({ path: join(output, "split-view.png") });
  const exportBounds = await page.getByRole("button", { name: "Export", exact: true }).boundingBox();
  assert.ok(exportBounds && exportBounds.x + exportBounds.width <= 600);
  report.checks.push("600px split-view export remains reachable");
  assert.equal(report.errors.length, 0);
  report.pass = true;
} finally {
  clearTimeout(watchdog); await browser.close();
  await writeFile(join(output, "report.json"), JSON.stringify(report, null, 2));
  console.log(output); console.log(JSON.stringify(report, null, 2));
}
